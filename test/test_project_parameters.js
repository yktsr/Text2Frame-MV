const chai = require('chai')
const expect = chai.expect
const fs = require('fs')
const os = require('os')
const path = require('path')

/* ツクールの外(CLI / VS Code 拡張 / t2f-sync / MCP)で、ゲーム自身の設定を見ているか。
 *
 * 見ていなかった。ツクール側で「既定の背景」を透明にしているプロジェクトは、
 * Frame2Text が `<背景: 透明>` を省く(省いてもプラグインが透明を補うので、ツクールの中では
 * 往復する)。そのテキストをツクールの外から反映すると、補う値が出荷時の「ウインドウ」になり、
 * **全部のメッセージウィンドウが黙ってウインドウに倒れた**。コメント文字も同じ穴で、
 * `%` 以外にしている人はコメント行が本文として反映される。
 *
 * PluginManager を置かない = ライブラリ分岐(test/test_json_eq.js と同じ)。
 * ツクールの中ではプラグインが生きた値を持っているので、そちらは触らない。 */
const text2frame = require('../Text2Frame.js')
const frame2text = require('../Frame2Text.js')

describe('the game\'s own Text2Frame settings', function () {
  let tmp

  /** ツクールが書く js/plugins.js の形。plugins を渡さなければ js/ ごと作らない。 */
  const project = function (plugins) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 't2f-params-'))
    if (plugins !== undefined) {
      fs.mkdirSync(path.join(root, 'js'))
      fs.writeFileSync(path.join(root, 'js', 'plugins.js'), plugins)
    }
    tmp.push(root)
    return root
  }

  /** Text2Frame の項目を含む plugins.js。status を false にすると切ってある状態。 */
  const pluginsJs = function (parameters, status) {
    const list = [
      { name: 'Community_Basic', status: true, description: '', parameters: { cacheLimit: '10' } },
      { name: 'Text2Frame', status: status !== false, description: '', parameters }
    ]
    return '//=====\n// Generated by RPG Maker.\n//=====\n\nvar $plugins =\n' +
      JSON.stringify(list, null, 1) + ';\n'
  }

  /* 出荷時の既定。これと違う値を入れたときだけ、読めているかどうかが分かる。 */
  const SHIPPED = { background: 0, position: 2 }
  /* プロジェクトが変えている値。背景=透明(2)、位置=上(0)、コメント文字=# 。 */
  const CHANGED = { background: 2, position: 0 }
  const changedParameters = {
    'Default Window Position': '上',
    'Default Background': '透明',
    'Comment Out Char': '#'
  }

  const headOf = function (root) {
    const opts = root === undefined ? undefined : { gameRoot: root }
    return text2frame.compile('こんにちは', opts)[0].parameters
  }

  /** コメント文字が何になっているか。消えた行で分かる。 */
  const bodyOf = function (root) {
    const opts = root === undefined ? undefined : { gameRoot: root }
    return text2frame.compile('%パーセントの行\n#シャープの行', opts)
      .filter(function (c) { return c.code === 401 })
      .map(function (c) { return c.parameters[0] })
  }

  beforeEach(function () { tmp = [] })
  afterEach(function () {
    tmp.forEach(function (dir) {
      try { fs.rmSync(dir, { recursive: true, force: true }) } catch (e) { /* ignore */ }
    })
  })

  /* これが本命。報告された壊れ方そのもの。 */
  it('fills in what the game itself would fill in', function () {
    const root = project(pluginsJs(changedParameters))

    const head = headOf(root)

    expect(head[2], '背景').to.equal(CHANGED.background)
    expect(head[3], '位置').to.equal(CHANGED.position)
  })

  it('takes the comment character from the game too', function () {
    const root = project(pluginsJs(changedParameters))

    // # がコメントなので、消えるのは # の行。% の行は本文として残る。
    expect(bodyOf(root)).to.eql(['%パーセントの行'])
  })

  /* 取り出す側。プロジェクトが補う値と同じタグは省かれる(省いても往復する)。 */
  it('omits the tags the game would fill back in', function () {
    const root = project(pluginsJs(changedParameters))
    const list = [
      { code: 101, indent: 0, parameters: ['', 0, CHANGED.background, CHANGED.position, ''] },
      { code: 401, indent: 0, parameters: ['こんにちは'] },
      { code: 0, indent: 0, parameters: [] }
    ]

    const out = frame2text.decompile(list, true, { pretty: true, gameRoot: root })

    expect(out).to.not.contain('Background')
    expect(out).to.not.contain('WindowPosition')
  })

  /* 以下は「今の挙動のまま」を固定する。どれかが動いたら、読み口が要らない所まで出ている。 */

  it('keeps the shipped defaults when no game folder is given', function () {
    const head = headOf(undefined)

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
    expect(bodyOf(undefined)).to.eql(['#シャープの行'])
  })

  it('keeps the shipped defaults when the game has no js/plugins.js', function () {
    const head = headOf(project())

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })

  /* 本物のアクアリウムがこれ(47個のプラグインがあるが Text2Frame は入っていない)。 */
  it('keeps the shipped defaults when Text2Frame is not installed there', function () {
    const other = '//=====\nvar $plugins =\n' + JSON.stringify([
      { name: 'Community_Basic', status: true, description: '', parameters: {} },
      { name: 'MadeWithMv', status: false, description: '', parameters: {} }
    ], null, 1) + ';\n'

    const head = headOf(project(other))

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })

  /* 切ってあるプラグインはツクールでも動かないので、補う値も出荷時のまま。 */
  it('keeps the shipped defaults when the plugin is switched off', function () {
    const head = headOf(project(pluginsJs(changedParameters, false)))

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })

  it('does not fall over on a js/plugins.js it cannot read', function () {
    const head = headOf(project('var $plugins = [ {{{ broken'))

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })

  /* 別名の表に無い値。「ウィンドウ」(小さい ィ)は在りそうで無い。
   * ここで投げると、設定のささいな間違いが「このプロジェクトは反映できない」になる。 */
  it('does not fall over on a value it does not know', function () {
    const root = project(pluginsJs({
      'Default Window Position': '下',
      'Default Background': 'ウィンドウ',
      'Comment Out Char': '#'
    }))

    const head = headOf(root)

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
    // 3つで1組。1つ読めなければコメント文字も入れない(反映と取り出しが別の
    // プロジェクトに居ることになるため)。
    expect(bodyOf(root)).to.eql(['#シャープの行'])
  })

  /* 1つのプロセスで2つのゲームを扱う(拡張は複数のフォルダを同時に開ける)。
   * 前のゲームの値が残ると、それはいま直している壊れ方そのもの。 */
  it('does not carry one game\'s settings into another', function () {
    const changed = project(pluginsJs(changedParameters))
    const plain = project()

    headOf(changed)
    const head = headOf(plain)

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })
})
