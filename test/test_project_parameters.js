const chai = require('chai')
const expect = chai.expect
const fs = require('fs')
const os = require('os')
const path = require('path')

/* ツクールの外(CLI / VS Code 拡張 / t2f-sync / MCP)で、ゲーム自身の設定を見ているか。
 *
 * 見ていなかった。ツクール側で「既定の背景」を透明にしているプロジェクトは、
 * Frame2Text が `<背景: 透明>` を省く(省いてもプラグインが透明を補うので、ツクールの中では
 * 往復する)。そのテキストをツクールの外から反映すると、補う値が出荷時の「ウインドウ」になり、
 * **全部のメッセージウィンドウが黙ってウインドウに倒れた**。コメント文字も同じ穴で、
 * `%` 以外にしている人はコメント行が本文として反映される。
 *
 * PluginManager を置かない = ライブラリ分岐(test/test_json_eq.js と同じ)。
 * ツクールの中ではプラグインが生きた値を持っているので、そちらは触らない。 */
const text2frame = require('../Text2Frame.js')
const frame2text = require('../Frame2Text.js')

describe('the game\'s own Text2Frame settings', function () {
  let tmp

  /** プラグインの中身は見ないので、実在することだけが要る。 */
  const installed = function (root, names) {
    const dir = path.join(root, 'js', 'plugins')
    fs.mkdirSync(dir, { recursive: true })
    names.forEach(function (name) {
      fs.writeFileSync(path.join(dir, name + '.js'), '// ' + name + '\n')
    })
  }

  /* ツクールが書く js/plugins.js の形。plugins を渡さなければ js/ ごと作らない。
   * 設定が効くには plugins.js の項目とプラグインの実在の両方が要るので、
   * 既定で Text2Frame を入れた形にする(入れない形は opts.install で作る)。 */
  const project = function (plugins, opts) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 't2f-params-'))
    if (plugins !== undefined) {
      fs.mkdirSync(path.join(root, 'js'))
      fs.writeFileSync(path.join(root, 'js', 'plugins.js'), plugins)
      installed(root, (opts && opts.install) || ['Text2Frame'])
    }
    tmp.push(root)
    return root
  }

  /** Text2Frame の項目を含む plugins.js。status を false にすると切ってある状態。 */
  const pluginsJs = function (parameters, status) {
    const list = [
      { name: 'Community_Basic', status: true, description: '', parameters: { cacheLimit: '10' } },
      { name: 'Text2Frame', status: status !== false, description: '', parameters }
    ]
    return '//=====\n// Generated by RPG Maker.\n//=====\n\nvar $plugins =\n' +
      JSON.stringify(list, null, 1) + ';\n'
  }

  /* 出荷時の既定。これと違う値を入れたときだけ、読めているかどうかが分かる。 */
  const SHIPPED = { background: 0, position: 2 }
  /* プロジェクトが変えている値。背景=透明(2)、位置=上(0)、コメント文字=# 。 */
  const CHANGED = { background: 2, position: 0 }
  const changedParameters = {
    'Default Window Position': '上',
    'Default Background': '透明',
    'Comment Out Char': '#'
  }

  /** Frame2Text の項目を含む plugins.js。取り出しの見せ方はこちらの設定が決める。 */
  const pullPluginsJs = function (parameters) {
    const list = [
      { name: 'Community_Basic', status: true, description: '', parameters: { cacheLimit: '10' } },
      { name: 'Frame2Text', status: true, description: '', parameters }
    ]
    return 'var $plugins =\n' + JSON.stringify(list, null, 1) + ';\n'
  }

  const headOf = function (root) {
    const opts = root === undefined ? undefined : { gameRoot: root }
    return text2frame.compile('こんにちは', opts)[0].parameters
  }

  /** コメント文字が何になっているか。消えた行で分かる。 */
  const bodyOf = function (root) {
    const opts = root === undefined ? undefined : { gameRoot: root }
    return text2frame.compile('%パーセントの行\n#シャープの行', opts)
      .filter(function (c) { return c.code === 401 })
      .map(function (c) { return c.parameters[0] })
  }

  beforeEach(function () { tmp = [] })
  afterEach(function () {
    tmp.forEach(function (dir) {
      try { fs.rmSync(dir, { recursive: true, force: true }) } catch (e) { /* ignore */ }
    })
  })

  /* これが本命。報告された壊れ方そのもの。 */
  it('fills in what the game itself would fill in', function () {
    const root = project(pluginsJs(changedParameters))

    const head = headOf(root)

    expect(head[2], '背景').to.equal(CHANGED.background)
    expect(head[3], '位置').to.equal(CHANGED.position)
  })

  it('takes the comment character from the game too', function () {
    const root = project(pluginsJs(changedParameters))

    // # がコメントなので、消えるのは # の行。% の行は本文として残る。
    expect(bodyOf(root)).to.eql(['%パーセントの行'])
  })

  /* 取り出す側。プロジェクトが補う値と同じタグは省かれる(省いても往復する)。 */
  it('omits the tags the game would fill back in', function () {
    const root = project(pluginsJs(changedParameters))
    const list = [
      { code: 101, indent: 0, parameters: ['', 0, CHANGED.background, CHANGED.position, ''] },
      { code: 401, indent: 0, parameters: ['こんにちは'] },
      { code: 0, indent: 0, parameters: [] }
    ]

    const out = frame2text.decompile(list, true, { pretty: true, gameRoot: root })

    expect(out).to.not.contain('Background')
    expect(out).to.not.contain('WindowPosition')
  })

  /* 呼び手が言い直した値は、ゲームの設定より強い。
   *
   *   明示したオプション > ゲームの plugins.js > 出荷時の既定
   *
   * 入口(CLI の旗・拡張の設定)はこの上に乗るだけなので、順番はここで固める。 */
  describe('a value the caller spells out', function () {
    it('wins over what the game says', function () {
      const root = project(pluginsJs(changedParameters))

      const head = text2frame.compile('こんにちは', {
        gameRoot: root,
        background: 'ウインドウ',
        windowPosition: '下'
      })[0].parameters

      expect(head[2], '背景').to.equal(SHIPPED.background)
      expect(head[3], '位置').to.equal(SHIPPED.position)
    })

    it('wins one field at a time, leaving the game to say the rest', function () {
      const root = project(pluginsJs(changedParameters))

      const head = text2frame.compile('こんにちは', { gameRoot: root, background: 'ウインドウ' })[0].parameters

      expect(head[2], '明示した背景').to.equal(SHIPPED.background)
      expect(head[3], 'ゲームの位置').to.equal(CHANGED.position)
    })

    it('says which comment character to use, over the game and the shipped one', function () {
      const root = project(pluginsJs(changedParameters))

      // ゲームは # と言っているが、呼び手が % と言ったので消えるのは % の行。
      expect(text2frame.compile('%パーセントの行\n#シャープの行', { gameRoot: root, commentOutChar: '%' })
        .filter(function (c) { return c.code === 401 })
        .map(function (c) { return c.parameters[0] })).to.eql(['#シャープの行'])
    })

    /* プラグインを入れていないゲーム(本物のアクアリウム)でも、入口から言えば効く。 */
    it('works on a game that has no Text2Frame at all', function () {
      const head = text2frame.compile('こんにちは', { background: '透明', windowPosition: '上' })[0].parameters

      expect(head[2]).to.equal(CHANGED.background)
      expect(head[3]).to.equal(CHANGED.position)
    })

    /* 空文字は「未設定」。拡張の設定が未設定を空文字で表すので、そのまま渡せるようにする。 */
    it('treats an empty string as nothing said', function () {
      const root = project(pluginsJs(changedParameters))

      const head = text2frame.compile('こんにちは', { gameRoot: root, background: '' })[0].parameters

      expect(head[2]).to.equal(CHANGED.background)
    })

    /* ゲームの設定は黙って既定に戻すが、利用者が打ったものは黙って落とさない。 */
    it('refuses a value it cannot read, instead of quietly using another one', function () {
      expect(function () {
        text2frame.compile('こんにちは', { background: 'ウィンドウ' })
      }).to.throw(/background/)
    })

    it('leaves nothing behind after it refuses', function () {
      try {
        text2frame.compile('こんにちは', { background: 'ウィンドウ' })
      } catch (e) { /* 断られるのが正しい */ }

      const head = headOf(undefined)

      expect(head[2]).to.equal(SHIPPED.background)
      expect(head[3]).to.equal(SHIPPED.position)
    })

    /* 取り出す側にも同じ順番で効かないと、省く基準と補う基準が食い違う。 */
    it('decides what the pull omits, the same way', function () {
      const root = project(pluginsJs(changedParameters))
      const list = [
        { code: 101, indent: 0, parameters: ['', 0, SHIPPED.background, SHIPPED.position, ''] },
        { code: 401, indent: 0, parameters: ['こんにちは'] },
        { code: 0, indent: 0, parameters: [] }
      ]

      // ゲームは透明/上と言うが、呼び手がウインドウ/下と言ったので、その2つは省かれる。
      const out = frame2text.decompile(list, true, {
        pretty: true,
        gameRoot: root,
        background: 'ウインドウ',
        windowPosition: '下'
      })

      expect(out).to.not.contain('Background')
      expect(out).to.not.contain('WindowPosition')
    })
  })

  /* 取り出しの見せ方は、ゲームの Frame2Text の設定にも従う。
   * ここは誰も読んでいなかった ── 拡張だけが設定を渡し、CLI は旗の既定を、
   * t2f-sync と MCP は何も渡さずライブラリの固定値に落ちていた。 */
  describe('the game\'s own Frame2Text settings', function () {
    /* 背景が既定と違う(暗くする)ので、タグは必ず書かれる。言語だけが変わる。 */
    const darkWindow = [
      { code: 101, indent: 0, parameters: ['', 0, 1, SHIPPED.position, ''] },
      { code: 401, indent: 0, parameters: ['こんにちは'] },
      { code: 0, indent: 0, parameters: [] }
    ]
    /* 背景も位置も出荷時の既定と同じ。省くかどうかでタグの有無が変わる。 */
    const plainWindow = [
      { code: 101, indent: 0, parameters: ['', 0, SHIPPED.background, SHIPPED.position, ''] },
      { code: 401, indent: 0, parameters: ['こんにちは'] },
      { code: 0, indent: 0, parameters: [] }
    ]
    const pullFrom = function (root, list, englishTag) {
      return frame2text.decompile(list, englishTag, { pretty: true, gameRoot: root })
    }

    it('takes the tag language from the game when nobody says', function () {
      const root = project(pullPluginsJs({ EnglishTag: 'false' }), { install: ['Frame2Text'] })

      expect(pullFrom(root, darkWindow, undefined)).to.contain('背景')
    })

    it('still lets the caller say otherwise', function () {
      const root = project(pullPluginsJs({ EnglishTag: 'false' }), { install: ['Frame2Text'] })

      expect(pullFrom(root, darkWindow, true)).to.contain('Background')
    })

    it('takes "write the tags even when they match" from the game', function () {
      const root = project(pullPluginsJs({ EnglishTag: 'true', OmitDefaultTags: 'false' }),
        { install: ['Frame2Text'] })

      expect(pullFrom(root, plainWindow, undefined)).to.contain('Background')
    })

    it('still lets the caller say otherwise about omitting', function () {
      const root = project(pullPluginsJs({ EnglishTag: 'true', OmitDefaultTags: 'false' }),
        { install: ['Frame2Text'] })

      const out = frame2text.decompile(plainWindow, undefined, { pretty: true, gameRoot: root, omitDefaults: true })

      expect(out).to.not.contain('Background')
    })

    /* 項目はあるが鍵が書かれていない形(Project1 の plugins.js がこれ)。
     * 組にすると、ここで言語まで読めなくなる。 */
    it('leaves a key the game does not write alone', function () {
      const root = project(pullPluginsJs({ EnglishTag: 'false' }), { install: ['Frame2Text'] })

      // 言語は読む(日本語)。省略は書かれていないので今までどおり省く。
      expect(pullFrom(root, plainWindow, undefined)).to.not.contain('背景')
      expect(pullFrom(root, darkWindow, undefined)).to.contain('背景')
    })

    /* 本物の kindworld がこれ(Text2Frame は入っているが Frame2Text は入っていない)。 */
    it('keeps the shipped behaviour when Frame2Text is not installed there', function () {
      const root = project(pluginsJs(changedParameters))

      expect(pullFrom(root, darkWindow, undefined)).to.contain('Background')
    })

    it('does not carry one game\'s settings into another', function () {
      const japanese = project(pullPluginsJs({ EnglishTag: 'false' }), { install: ['Frame2Text'] })
      const plain = project()

      pullFrom(japanese, darkWindow, undefined)

      expect(pullFrom(plain, darkWindow, undefined)).to.contain('Background')
    })
  })

  /* 5つの設定 × 3つの出どころなので、どこから来たかが見えないと追えない。
   * とくに「設定は書いてあるがプラグインが入っていない」は、**読まなくなる唯一の形**。 */
  describe('saying where each value came from', function () {
    const resolve = text2frame._internal.resolveProjectParameters
    const say = text2frame._internal.describeProjectParameters
    const pull = frame2text._internal.resolvePullParameters

    it('names the game as the source when the game says it', function () {
      const report = resolve(project(pluginsJs(changedParameters)))

      expect(report.values.background).to.equal('透明')
      expect(report.from.background).to.equal('ゲーム')
      expect(report.settingsIgnored).to.equal(false)
      expect(report.differs).to.eql([])
    })

    it('names the caller when the caller says it', function () {
      const report = resolve(project(pluginsJs(changedParameters)), { background: 'ウインドウ' })

      expect(report.from.background).to.equal('明示')
      expect(report.from.windowPosition).to.equal('ゲーム')
    })

    it('names the shipped default when nothing says it', function () {
      const report = resolve(project())

      expect(report.from.background).to.equal('出荷時')
    })

    /* 2つ目の条件を足したことで読まなくなる唯一の形。黙って倒れさせない。 */
    it('says the settings are there but the plugin is not', function () {
      const report = resolve(project(pluginsJs(changedParameters), { install: [] }))

      expect(report.settingsIgnored).to.equal(true)
      expect(report.from.background).to.equal('出荷時')
      expect(say(report).notes.join('\n')).to.contain('js/plugins/Text2Frame.js')
    })

    /* 片方の入口だけで指定すると、省くタグと補う値が食い違う。構造では防げないので言う。 */
    it('says when what the caller said differs from the game', function () {
      const report = resolve(project(pluginsJs(changedParameters)), { background: 'ウインドウ' })

      expect(report.differs).to.eql(['background'])
      expect(say(report).notes.join('\n')).to.contain('取り出しと反映')
    })

    it('says nothing extra when the caller repeats what the game says', function () {
      const report = resolve(project(pluginsJs(changedParameters)), { background: '透明' })

      expect(report.differs).to.eql([])
      expect(say(report).notes).to.eql([])
    })

    it('answers the same way for the pull side', function () {
      const root = project(pullPluginsJs({ EnglishTag: 'false' }), { install: ['Frame2Text'] })

      const report = pull(root)

      expect(report.plugin).to.equal('Frame2Text')
      expect(report.values.englishTag).to.equal(false)
      expect(report.from.englishTag).to.equal('ゲーム')
      // 鍵が書かれていないものは出荷時のまま。
      expect(report.from.omitDefaults).to.equal('出荷時')
      expect(say(report).line).to.contain('Frame2Text:')
    })

    it('names the caller on the pull side too', function () {
      const root = project(pullPluginsJs({ EnglishTag: 'false' }), { install: ['Frame2Text'] })

      const report = pull(root, { englishTag: true })

      expect(report.from.englishTag).to.equal('明示')
      expect(report.differs).to.eql(['englishTag'])
    })
  })

  /* 以下は「今の挙動のまま」を固定する。どれかが動いたら、読み口が要らない所まで出ている。 */

  it('keeps the shipped defaults when no game folder is given', function () {
    const head = headOf(undefined)

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
    expect(bodyOf(undefined)).to.eql(['#シャープの行'])
  })

  it('keeps the shipped defaults when the game has no js/plugins.js', function () {
    const head = headOf(project())

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })

  /* 本物のアクアリウムがこれ(47個のプラグインがあるが Text2Frame は入っていない)。 */
  it('keeps the shipped defaults when Text2Frame is not installed there', function () {
    const other = '//=====\nvar $plugins =\n' + JSON.stringify([
      { name: 'Community_Basic', status: true, description: '', parameters: {} },
      { name: 'MadeWithMv', status: false, description: '', parameters: {} }
    ], null, 1) + ';\n'

    const head = headOf(project(other))

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })

  /* 条件は2つで、どちらも要る。片方だけのときは出荷時の既定のまま。 */

  /* 項目だけ残してプラグインを消した形。その設定はゲームの中で何も動かしていない。 */
  it('keeps the shipped defaults when the plugin itself is not there', function () {
    const root = project(pluginsJs(changedParameters), { install: [] })

    const head = headOf(root)

    expect(head[2], '背景').to.equal(SHIPPED.background)
    expect(head[3], '位置').to.equal(SHIPPED.position)
    expect(bodyOf(root), 'コメント文字').to.eql(['#シャープの行'])
  })

  /* プラグインを置いただけでツクールに登録していない形。パラメータはどこにも無い。 */
  it('keeps the shipped defaults when the plugin is there but not registered', function () {
    const other = '//=====\nvar $plugins =\n' + JSON.stringify([
      { name: 'Community_Basic', status: true, description: '', parameters: {} }
    ], null, 1) + ';\n'

    const head = headOf(project(other, { install: ['Text2Frame'] }))

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })

  /* 覚えた答えは plugins.js とプラグインの両方で確かめる。plugins.js だけで覚えると、
   * プラグインを消しただけの人のところで古い答えを返し続ける。 */
  it('forgets what it read when the plugin is removed afterwards', function () {
    const root = project(pluginsJs(changedParameters))
    expect(headOf(root)[2], '消す前').to.equal(CHANGED.background)

    fs.rmSync(path.join(root, 'js', 'plugins', 'Text2Frame.js'))

    expect(headOf(root)[2], '消した後').to.equal(SHIPPED.background)
  })

  /* 切ってあるプラグインはツクールでも動かないので、補う値も出荷時のまま。 */
  it('keeps the shipped defaults when the plugin is switched off', function () {
    const head = headOf(project(pluginsJs(changedParameters, false)))

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })

  it('does not fall over on a js/plugins.js it cannot read', function () {
    const head = headOf(project('var $plugins = [ {{{ broken'))

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })

  /* 別名の表に無い値。「ウィンドウ」(小さい ィ)は在りそうで無い。
   * ここで投げると、設定のささいな間違いが「このプロジェクトは反映できない」になる。 */
  it('does not fall over on a value it does not know', function () {
    const root = project(pluginsJs({
      'Default Window Position': '下',
      'Default Background': 'ウィンドウ',
      'Comment Out Char': '#'
    }))

    const head = headOf(root)

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
    // 3つで1組。1つ読めなければコメント文字も入れない(反映と取り出しが別の
    // プロジェクトに居ることになるため)。
    expect(bodyOf(root)).to.eql(['#シャープの行'])
  })

  /* 1つのプロセスで2つのゲームを扱う(拡張は複数のフォルダを同時に開ける)。
   * 前のゲームの値が残ると、それはいま直している壊れ方そのもの。 */
  it('does not carry one game\'s settings into another', function () {
    const changed = project(pluginsJs(changedParameters))
    const plain = project()

    headOf(changed)
    const head = headOf(plain)

    expect(head[2]).to.equal(SHIPPED.background)
    expect(head[3]).to.equal(SHIPPED.position)
  })
})
