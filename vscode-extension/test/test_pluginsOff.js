const { expect } = require('chai')

/* テストプレイのときだけプラグインを切る。
 *
 * ツクール本体(nw.js)の中でだけ動く作りのプラグインがある ── Node の `require` を使うものが
 * それで、ブラウザには `require` が無い。そういうプラグインがゲームの動きに関わっていると、
 * ブラウザで動かすテストプレイはそこで止まる(実物のゲームで、セーブの読み込みに関わって
 * いて読めなかった)。**プラグインが悪いのではなく、動かす場所が違うだけ。**
 *
 * **ゲームのフォルダは書き換えない。** 配るときに中身だけ差し替える。 */
const { pluginsOff, pluginNames } = require('../out/db/pluginsOff')

describe('turning a plugin off for the test play', function () {
  /** ツクールが書く形。 */
  const listOf = function (plugins) {
    return '// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n' +
      JSON.stringify(plugins, null, 0) + ';\n'
  }
  const plugins = function (source) {
    return JSON.parse(/\$plugins\s*=\s*(\[[\s\S]*\])\s*;/.exec(source)[1])
  }
  const THREE = [
    { name: 'PluginOne', status: true, description: 'でばっぐ', parameters: { JsonSave: 'true' } },
    { name: 'PluginTwo', status: true, description: 'はんぶん', parameters: {} },
    { name: 'PluginThree', status: false, description: 'ひなた', parameters: {} }
  ]

  it('turns off only the plugin it was told to', function () {
    const after = plugins(pluginsOff(listOf(THREE), ['PluginOne']))

    expect(after.map(function (p) { return [p.name, p.status] }))
      .to.eql([['PluginOne', false], ['PluginTwo', true], ['PluginThree', false]])
  })

  /* 切るだけで、ほかは1つも変えない(パラメータを落とすと、そのゲームの設定が消える)。 */
  it('keeps everything else about the plugin', function () {
    const after = plugins(pluginsOff(listOf(THREE), ['PluginOne']))

    expect(after[0].description).to.equal('でばっぐ')
    expect(after[0].parameters).to.eql({ JsonSave: 'true' })
  })

  /* 設定に書く名前は、ファイル名のつもりでも通す。 */
  it('takes the name with or without .js, in any case', function () {
    const after = plugins(pluginsOff(listOf(THREE), ['pluginone.js', ' PluginTwo ']))

    expect(after.map(function (p) { return p.status })).to.eql([false, false, false])
  })

  it('leaves the file alone when it was told nothing', function () {
    const source = listOf(THREE)

    expect(pluginsOff(source, [])).to.equal(source)
    expect(pluginsOff(source, ['NoSuchPlugin'])).to.equal(source)
  })

  /* 切れないことより、配るものを壊さない方が大事。 */
  it('leaves a file it cannot read alone', function () {
    const broken = 'var $plugins =\n[{"name": "PluginOne", ;\n'

    expect(pluginsOff(broken, ['PluginOne'])).to.equal(broken)
    expect(pluginsOff('なにか別のファイル', ['PluginOne'])).to.equal('なにか別のファイル')
  })

  /* 前後の行は残す。ツクールが書いた注記を消すと、人が見て驚く。 */
  it('keeps the lines around the list', function () {
    const after = pluginsOff(listOf(THREE), ['PluginTwo'])

    expect(after).to.contain('// Generated by RPG Maker.')
    expect(after).to.contain('var $plugins =')
    expect(after.trim().slice(-1)).to.equal(';')
  })

  describe('the names in the file', function () {
    it('lists them in order', function () {
      expect(pluginNames(listOf(THREE))).to.eql(['PluginOne', 'PluginTwo', 'PluginThree'])
    })

    it('says nothing for a file it cannot read', function () {
      expect(pluginNames('ただのメモ')).to.eql([])
    })

    /* ツクールのプラグイン管理では、区切りの行を入れて束ねられる。あれはプラグイン
     * ではないので、選ばせると一覧が読めなくなる(実物のゲームで88件のうち14件)。 */
    it('leaves out the rows that are only there to group the list', function () {
      const source = listOf([
        { name: '-----------------------', status: false, description: '', parameters: {} },
        { name: '-CORE', status: false, description: '', parameters: {} },
        { name: 'PluginOne', status: true, description: '', parameters: {} },
        { name: ' ', status: false, description: '', parameters: {} }
      ])

      expect(pluginNames(source)).to.eql(['PluginOne'])
    })
  })
})
