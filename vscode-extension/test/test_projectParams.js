const { expect } = require('chai')
const fs = require('fs')
const path = require('path')

/* ゲームの js/plugins.js から読む設定。
 *
 * `%` 以外のコメント文字にしている人の画面では、知らないと**コメント行が本文として
 * 色分けされ、本文がコメントとして消える**。反映の側は本体(Text2Frame.js)が同じファイルを
 * 読んで直したので、画面の側も同じ値を見る。
 *
 * パラメータの名前は本体が宣言しているものなので、ここで本体のヘルプと突き合わせる。
 * 名前を1文字間違えると、読めないまま既定の `%` に落ちて黙って元の症状に戻る。 */
const { parsePlugins, enabledPlugin, commentOutCharIn, COMMENT_OUT_CHAR, TEXT2FRAME } = require('../out/db/projectParams')
const { autoWrapPlugin } = require('../out/db/messageFit')

const repoRoot = path.resolve(__dirname, '..', '..')

const pluginsJs = function (list) {
    return '//=====\n// Generated by RPG Maker.\n//=====\n\nvar $plugins =\n' + JSON.stringify(list, null, 1) + ';\n'
}

const t2f = function (parameters, status) {
    return pluginsJs([
        { name: 'Community_Basic', status: true, description: '', parameters: {} },
        { name: TEXT2FRAME, status: status !== false, description: '', parameters }
    ])
}

describe('the settings in the game\'s js/plugins.js', function () {
    /* 本体が宣言している名前と同じでなければ、読めないまま既定に落ちる。 */
    it('names the parameter the way the plugin declares it', function () {
        const help = fs.readFileSync(path.join(repoRoot, 'Text2Frame.js'), 'utf8')
        const declared = (help.match(/^\s*\*\s*@param\s+(.+?)\s*$/gm) || [])
            .map(function (line) { return line.replace(/^\s*\*\s*@param\s+/, '').trim() })

        expect(declared, '@param が拾えません(探し方が壊れたかも)').to.not.eql([])
        expect(declared, COMMENT_OUT_CHAR + ' というパラメータを本体が宣言していません').to.include(COMMENT_OUT_CHAR)
    })

    /* 相手のプラグインの名前も本体に合わせる(ツクールは @plugindesc のファイル名で呼ぶ)。 */
    it('looks for the plugin by the name RPG Maker uses', function () {
        expect(fs.existsSync(path.join(repoRoot, TEXT2FRAME + '.js'))).to.equal(true)
    })

    it('reads the comment character the project set', function () {
        expect(commentOutCharIn(t2f({ 'Comment Out Char': '#' }))).to.equal('#')
    })

    it('says nothing when the project left it at the shipped value', function () {
        // 呼び側が既定の % を使う。ここで '%' を返しても同じだが、
        // 「設定されていない」と「% に設定した」を分けない方が呼び側が簡単。
        expect(commentOutCharIn(t2f({ 'Comment Out Char': '%' }))).to.equal('%')
    })

    it('says nothing when the plugin is not installed', function () {
        expect(commentOutCharIn(pluginsJs([{ name: 'Community_Basic', status: true, parameters: {} }]))).to.equal(undefined)
    })

    it('says nothing when the plugin is switched off', function () {
        expect(commentOutCharIn(t2f({ 'Comment Out Char': '#' }, false))).to.equal(undefined)
    })

    it('says nothing when the value is empty', function () {
        expect(commentOutCharIn(t2f({ 'Comment Out Char': '' }))).to.equal(undefined)
    })

    it('does not fall over on a file it cannot read', function () {
        expect(parsePlugins('var $plugins = [ {{{ broken')).to.eql([])
        expect(commentOutCharIn('なんでもない文字列')).to.equal(undefined)
        expect(enabledPlugin('', TEXT2FRAME)).to.equal(undefined)
    })

    /* 自動改行の見分けも同じ読み方に寄せた。片方だけ壊れないことを見る。 */
    it('still finds an auto-wrap plugin with the shared reader', function () {
        const source = pluginsJs([{ name: 'YEP_WordWrap', status: true, parameters: {} }])

        expect(autoWrapPlugin(source)).to.equal('YEP_WordWrap')
        expect(autoWrapPlugin('こわれている')).to.equal(undefined)
    })
})

/* コメント文字を渡さずに呼ぶと、その画面だけ `%` のままになる。例外は出ず、見た目だけが
 * 静かに変わるので、呼び出しを機械で数える。 */
describe('telling the editor features which comment character', function () {
    const srcDir = path.resolve(__dirname, '..', 'src')
    const CALLS = [
        /\blineKinds\s*\(/, /\btagLines\s*\(/, /\bscanLines\s*\(/, /\breadStructure\s*\(/,
        /\blabelLine\s*\(/, /\bscanSelfSwitchLines\s*\(/, /\busageHits\s*\(/,
        /\bbracketProblems\s*\(/, /\bbasicProblems\s*\(/, /\bmessageProblems\s*\(/
    ]
    const WINDOW = 6

    const files = function () {
        const out = []
        const walk = function (dir) {
            fs.readdirSync(dir, { withFileTypes: true }).forEach(function (entry) {
                const full = path.join(dir, entry.name)
                if (entry.isDirectory()) walk(full)
                else if (entry.name.endsWith('.ts')) out.push(full)
            })
        }
        walk(srcDir)
        return out
    }

    const hits = function () {
        const out = []
        files().forEach(function (file) {
            const lines = fs.readFileSync(file, 'utf8').split('\n')
            lines.forEach(function (line, index) {
                if (/^\s*(\/\/|\*|\/\*)/.test(line)) return
                if (!CALLS.some(function (re) { return re.test(line) })) return
                out.push({
                    where: path.relative(srcDir, file) + ':' + (index + 1),
                    line: line.trim(),
                    block: lines.slice(index, index + WINDOW).join('\n')
                })
            })
        })
        return out
    }

    it('passes it everywhere it reads lines', function () {
        const bad = hits().filter(function (h) { return !/comment/i.test(h.block) })

        expect(bad, 'コメント文字を渡していません:\n  ' + bad.map(function (h) { return h.where + '  ' + h.line }).join('\n  ') + '\n').to.eql([])
    })

    it('actually finds the calls it is looking for', function () {
        expect(hits().length, '呼び出しが見つかりません(探し方が壊れたかも)').to.be.greaterThan(10)
    })
})
